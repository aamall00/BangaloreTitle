import io
import logging
from datetime import datetime
from typing import Dict, List, Any

log = logging.getLogger(__name__)

try:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm, cm
    from reportlab.lib.enums import TA_LEFT, TA_CENTER, TA_RIGHT, TA_JUSTIFY
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
        HRFlowable, PageBreak, KeepTogether,
    )
    from reportlab.graphics.shapes import Drawing, Rect, String, Line, Circle
    from reportlab.graphics.charts.barcharts import VerticalBarChart
    from reportlab.graphics import renderPDF
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False
    log.warning("reportlab not installed. PDF generation unavailable.")

RISK_HEX = {
    "LOW":      "#22c55e",
    "MEDIUM":   "#f59e0b",
    "HIGH":     "#ef4444",
    "CRITICAL": "#7c3aed",
}

RISK_RGB = {
    "LOW":      colors.HexColor("#22c55e"),
    "MEDIUM":   colors.HexColor("#f59e0b"),
    "HIGH":     colors.HexColor("#ef4444"),
    "CRITICAL": colors.HexColor("#7c3aed"),
}

SEV_RGB = {
    "CRITICAL": colors.HexColor("#7c3aed"),
    "HIGH":     colors.HexColor("#ef4444"),
    "MEDIUM":   colors.HexColor("#f59e0b"),
    "LOW":      colors.HexColor("#22c55e"),
}

DARK_BG  = colors.HexColor("#0f172a")
CARD_BG  = colors.HexColor("#1e293b")
BORDER   = colors.HexColor("#334155")
FG       = colors.HexColor("#f1f5f9")
MUTED    = colors.HexColor("#94a3b8")
PRIMARY  = colors.HexColor("#3b82f6")
WHITE    = colors.white


class PDFGenerator:
    def generate(self, analysis: Dict) -> bytes:
        if not REPORTLAB_AVAILABLE:
            return self._text_fallback(analysis)

        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=A4,
            leftMargin=15*mm, rightMargin=15*mm,
            topMargin=15*mm,  bottomMargin=20*mm,
            title="Karnataka Title Due Diligence Report",
            author="Bengaluru Title Scout",
        )

        styles = self._build_styles()
        story  = []

        story += self._build_cover(analysis, styles)
        story.append(PageBreak())
        story += self._build_summary_section(analysis, styles)
        story += self._build_scores_section(analysis, styles)
        story += self._build_flags_section(analysis, styles)
        story += self._build_ownership_chain_section(analysis, styles)
        story += self._build_legal_analysis_section(analysis, styles)
        story += self._build_recommendations_section(analysis, styles)
        story += self._build_footer_disclaimer(styles)

        doc.build(story, onFirstPage=self._page_template, onLaterPages=self._page_template)
        return buf.getvalue()

    def _page_template(self, canvas, doc):
        canvas.saveState()
        w, h = A4
        canvas.setFillColor(DARK_BG)
        canvas.rect(0, 0, w, h, fill=1, stroke=0)
        canvas.setFillColor(PRIMARY)
        canvas.rect(0, h - 8*mm, w, 8*mm, fill=1, stroke=0)
        canvas.setFont("Helvetica-Bold", 8)
        canvas.setFillColor(WHITE)
        canvas.drawString(15*mm, h - 5.5*mm, "BENGALURU TITLE SCOUT")
        canvas.drawRightString(w - 15*mm, h - 5.5*mm, f"CONFIDENTIAL — Page {doc.page}")
        canvas.setFillColor(BORDER)
        canvas.rect(0, 0, w, 8*mm, fill=1, stroke=0)
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(MUTED)
        canvas.drawString(15*mm, 2.5*mm, "This report is generated by AI and does not constitute legal advice. Engage a qualified Karnataka property lawyer for final title opinion.")
        canvas.restoreState()

    def _build_styles(self):
        styles = getSampleStyleSheet()
        custom = {
            "cover_title": ParagraphStyle("cover_title", fontName="Helvetica-Bold", fontSize=28, textColor=WHITE, spaceAfter=4, leading=34),
            "cover_sub":   ParagraphStyle("cover_sub",   fontName="Helvetica",      fontSize=12, textColor=MUTED,  spaceAfter=6),
            "section_hdr": ParagraphStyle("section_hdr", fontName="Helvetica-Bold", fontSize=13, textColor=PRIMARY, spaceBefore=14, spaceAfter=6, borderPad=2),
            "body":        ParagraphStyle("body",        fontName="Helvetica",      fontSize=9,  textColor=FG,    leading=14, spaceAfter=4, alignment=TA_JUSTIFY),
            "body_sm":     ParagraphStyle("body_sm",     fontName="Helvetica",      fontSize=8,  textColor=MUTED, leading=12),
            "label":       ParagraphStyle("label",       fontName="Helvetica-Bold", fontSize=8,  textColor=MUTED, spaceAfter=1),
            "value":       ParagraphStyle("value",       fontName="Helvetica",      fontSize=9,  textColor=FG),
            "flag_title":  ParagraphStyle("flag_title",  fontName="Helvetica-Bold", fontSize=10, textColor=WHITE, spaceAfter=2),
            "flag_body":   ParagraphStyle("flag_body",   fontName="Helvetica",      fontSize=8,  textColor=FG,    leading=12, alignment=TA_JUSTIFY),
            "flag_ref":    ParagraphStyle("flag_ref",    fontName="Helvetica-Oblique", fontSize=8, textColor=PRIMARY),
            "rec":         ParagraphStyle("rec",         fontName="Helvetica",      fontSize=9,  textColor=FG,    leading=13, leftIndent=10),
            "chain_name":  ParagraphStyle("chain_name",  fontName="Helvetica-Bold", fontSize=9,  textColor=WHITE),
            "chain_meta":  ParagraphStyle("chain_meta",  fontName="Helvetica",      fontSize=8,  textColor=MUTED),
        }
        return {**{k: styles[k] for k in styles.byName}, **custom}

    def _build_cover(self, analysis: Dict, styles) -> List:
        risk  = analysis.get("risk_level", "MEDIUM")
        color = RISK_RGB.get(risk, RISK_RGB["MEDIUM"])
        details = analysis.get("property_details", {})

        story = [Spacer(1, 20*mm)]

        d = Drawing(180*mm, 20*mm)
        d.add(Rect(0, 0, 180*mm, 20*mm, fillColor=color, strokeColor=None, rx=4, ry=4))
        d.add(String(8*mm, 6*mm, f"RISK LEVEL: {risk}", fontName="Helvetica-Bold", fontSize=16, fillColor=colors.white))
        story.append(d)
        story.append(Spacer(1, 8*mm))

        story.append(Paragraph("Karnataka Land Title", styles["cover_sub"]))
        story.append(Paragraph("Due Diligence Report", styles["cover_title"]))
        story.append(Spacer(1, 4*mm))

        survey = details.get("survey_number", "—")
        location = details.get("location", "Bengaluru, Karnataka")
        story.append(Paragraph(f"Survey No. {survey} &nbsp;•&nbsp; {location}", styles["cover_sub"]))
        story.append(Paragraph(f"Generated: {datetime.now().strftime('%d %B %Y, %I:%M %p')}", styles["cover_sub"]))
        story.append(Spacer(1, 6*mm))

        props = [
            ("Document Type",    analysis.get("document_type_detected", analysis.get("doc_type", "—"))),
            ("Extent",           details.get("extent", "—")),
            ("Document Number",  details.get("document_number", "—")),
            ("Date Range",       f"{details.get('earliest_date','—')} to {details.get('latest_date','—')}"),
            ("Flags Raised",     str(len(analysis.get("flags", [])))),
            ("Grant Land",       "YES ⚠" if details.get("is_grant_land") else "No"),
        ]
        tdata = [[Paragraph(k, styles["label"]), Paragraph(str(v), styles["value"])] for k, v in props]
        t = Table(tdata, colWidths=[45*mm, 125*mm])
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("ROWBACKGROUNDS", (0, 0), (-1, -1), [CARD_BG, colors.HexColor("#263347")]),
            ("BOX",    (0, 0), (-1, -1), 0.5, BORDER),
            ("GRID",   (0, 0), (-1, -1), 0.3, BORDER),
            ("TOPPADDING",    (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING",   (0, 0), (-1, -1), 8),
        ]))
        story.append(t)
        return story

    def _build_summary_section(self, analysis: Dict, styles) -> List:
        story = [Paragraph("Executive Summary", styles["section_hdr"])]
        summary = analysis.get("summary", "No summary available.")
        story.append(Paragraph(summary, styles["body"]))
        story.append(Spacer(1, 4*mm))
        return story

    def _build_scores_section(self, analysis: Dict, styles) -> List:
        scores = analysis.get("scores", {})
        if not scores:
            return []

        story = [Paragraph("Due Diligence Scores", styles["section_hdr"])]

        items = [
            ("Title Clarity",      scores.get("title_clarity", 0)),
            ("Chain Continuity",   scores.get("chain_continuity", 0)),
            ("Legal Compliance",   scores.get("legal_compliance", 0)),
        ]

        d = Drawing(170*mm, 60*mm)
        bar_w = 40*mm
        gap   = 15*mm
        start_x = 10*mm
        for i, (label, score) in enumerate(items):
            x = start_x + i * (bar_w + gap)
            bar_h = (score / 100) * 45*mm
            bar_color = colors.HexColor(
                "#22c55e" if score >= 75 else "#f59e0b" if score >= 50 else "#ef4444"
            )
            d.add(Rect(x, 10*mm, bar_w, 45*mm, fillColor=BORDER, strokeColor=None))
            d.add(Rect(x, 10*mm, bar_w, bar_h, fillColor=bar_color, strokeColor=None))
            d.add(String(x + bar_w/2, 3*mm, label, fontName="Helvetica", fontSize=7, fillColor=colors.HexColor("#94a3b8"), textAnchor="middle"))
            d.add(String(x + bar_w/2, bar_h + 12*mm, f"{score}", fontName="Helvetica-Bold", fontSize=11, fillColor=colors.white, textAnchor="middle"))

        story.append(d)
        story.append(Spacer(1, 4*mm))
        return story

    def _build_flags_section(self, analysis: Dict, styles) -> List:
        flags = analysis.get("flags", [])
        if not flags:
            story = [Paragraph("Risk Flags", styles["section_hdr"])]
            story.append(Paragraph("✅  No risk flags raised. Document passed all Karnataka legal checks.", styles["body"]))
            return story

        sev_order = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
        flags = sorted(flags, key=lambda f: sev_order.get(f.get("severity", "LOW"), 4))

        story = [Paragraph(f"Risk Flags ({len(flags)} found)", styles["section_hdr"])]

        for flag in flags:
            sev   = flag.get("severity", "MEDIUM")
            color = SEV_RGB.get(sev, SEV_RGB["MEDIUM"])
            bg    = colors.HexColor({
                "CRITICAL": "#1a0a2e", "HIGH": "#2d0a0a",
                "MEDIUM":   "#2d1f0a", "LOW":  "#0a2d0a",
            }.get(sev, "#1e293b"))

            rows = []
            rows.append([
                Paragraph(f"[{sev}]", ParagraphStyle("sev", fontName="Helvetica-Bold", fontSize=9, textColor=color)),
                Paragraph(flag.get("title", ""), styles["flag_title"]),
            ])
            rows.append(["", Paragraph(flag.get("description", ""), styles["flag_body"])])
            if flag.get("law_reference"):
                rows.append(["", Paragraph(f"Law: {flag['law_reference']}", styles["flag_ref"])])
            if flag.get("recommendation"):
                rows.append(["", Paragraph(f"Action: {flag['recommendation']}", styles["flag_body"])])

            t = Table(rows, colWidths=[18*mm, 152*mm])
            t.setStyle(TableStyle([
                ("BACKGROUND",    (0, 0), (-1, -1), bg),
                ("BOX",           (0, 0), (-1, -1), 1, color),
                ("TOPPADDING",    (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING",   (0, 0), (-1, -1), 8),
                ("VALIGN",        (0, 0), (-1, -1), "TOP"),
            ]))
            story.append(KeepTogether([t, Spacer(1, 3*mm)]))

        return story

    def _build_ownership_chain_section(self, analysis: Dict, styles) -> List:
        chain = analysis.get("ownership_chain", [])
        if not chain:
            return []

        story = [Paragraph(f"Ownership Chain ({len(chain)} entries)", styles["section_hdr"])]

        hdr = [
            Paragraph("#",            styles["label"]),
            Paragraph("Owner",        styles["label"]),
            Paragraph("Period",       styles["label"]),
            Paragraph("Document",     styles["label"]),
            Paragraph("Transfer",     styles["label"]),
            Paragraph("Issues",       styles["label"]),
        ]
        rows = [hdr]
        for i, entry in enumerate(chain):
            is_current = i == len(chain) - 1
            bg = colors.HexColor("#0a2d0a") if is_current else CARD_BG
            flag_text = entry.get("flag", "—") or "—"
            rows.append([
                Paragraph(str(i + 1), styles["chain_meta"]),
                Paragraph(entry.get("owner_name", "Unknown"), styles["chain_name"] if is_current else styles["value"]),
                Paragraph(entry.get("period", entry.get("from_date", "—")), styles["chain_meta"]),
                Paragraph(entry.get("document_type", entry.get("document_number", "—")), styles["chain_meta"]),
                Paragraph(entry.get("transfer_type", "—"), styles["chain_meta"]),
                Paragraph(flag_text, ParagraphStyle("fi", fontName="Helvetica", fontSize=7, textColor=colors.HexColor("#ef4444") if flag_text != "—" else MUTED)),
            ])

        t = Table(rows, colWidths=[10*mm, 45*mm, 30*mm, 35*mm, 25*mm, 25*mm])
        ts = TableStyle([
            ("BACKGROUND",    (0, 0), (-1, 0),  PRIMARY),
            ("TEXTCOLOR",     (0, 0), (-1, 0),  WHITE),
            ("ROWBACKGROUNDS",(0, 1), (-1, -1), [CARD_BG, colors.HexColor("#263347")]),
            ("BOX",           (0, 0), (-1, -1), 0.5, BORDER),
            ("GRID",          (0, 0), (-1, -1), 0.3, BORDER),
            ("TOPPADDING",    (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING",   (0, 0), (-1, -1), 6),
            ("VALIGN",        (0, 0), (-1, -1), "TOP"),
        ])
        t.setStyle(ts)
        story.append(t)
        story.append(Spacer(1, 4*mm))
        return story

    def _build_legal_analysis_section(self, analysis: Dict, styles) -> List:
        legal = analysis.get("legal_analysis", {})
        if not legal:
            return []

        story = [Paragraph("Detailed Legal Analysis", styles["section_hdr"])]

        sections = [
            ("ptcl_analysis",          "🛡  PTCL Act — SC/ST Grant Land"),
            ("land_reforms_analysis",  "⚖  Karnataka Land Reforms Act, 1961"),
            ("land_revenue_analysis",  "📋  Karnataka Land Revenue Act, 1964"),
            ("dc_conversion_analysis", "🗺  DC Conversion & Zoning"),
            ("encumbrance_analysis",   "🔗  Encumbrance & Liabilities"),
            ("rera_analysis",          "🏢  RERA Karnataka"),
        ]
        for key, label in sections:
            content = legal.get(key)
            if not content:
                continue
            story.append(Paragraph(label, ParagraphStyle("lh", fontName="Helvetica-Bold", fontSize=10, textColor=PRIMARY, spaceBefore=6, spaceAfter=3)))
            story.append(Paragraph(content, styles["body"]))

        return story

    def _build_recommendations_section(self, analysis: Dict, styles) -> List:
        recs = analysis.get("recommendations", [])
        if not recs:
            return []

        story = [Paragraph("Recommendations & Next Steps", styles["section_hdr"])]
        for i, rec in enumerate(recs, 1):
            story.append(Paragraph(f"{i}.  {rec}", styles["rec"]))
            story.append(Spacer(1, 2*mm))
        return story

    def _build_footer_disclaimer(self, styles) -> List:
        story = [
            Spacer(1, 6*mm),
            HRFlowable(width="100%", thickness=0.5, color=BORDER),
            Spacer(1, 3*mm),
            Paragraph(
                "<b>DISCLAIMER:</b> This report is generated by Bengaluru Title Scout using AI-assisted analysis of the provided documents. "
                "It does not constitute legal advice and should not be relied upon as a substitute for a formal title opinion from a qualified Karnataka "
                "property lawyer. The analysis is based on OCR-extracted text from the provided documents and may contain errors due to document quality "
                "or OCR limitations. Always verify the findings with original documents and relevant government records.",
                ParagraphStyle("disc", fontName="Helvetica", fontSize=7, textColor=MUTED, leading=10, alignment=TA_JUSTIFY),
            ),
        ]
        return story

    def _text_fallback(self, analysis: Dict) -> bytes:
        lines = [
            "BENGALURU TITLE SCOUT — TITLE DUE DILIGENCE REPORT",
            "=" * 60,
            f"Risk Level: {analysis.get('risk_level', 'UNKNOWN')}",
            f"Generated: {datetime.now().strftime('%d %B %Y')}",
            "",
            "SUMMARY",
            analysis.get("summary", "N/A"),
            "",
            "FLAGS",
        ]
        for f in analysis.get("flags", []):
            lines.append(f"[{f.get('severity')}] {f.get('title')}: {f.get('description')}")
        lines += ["", "RECOMMENDATIONS"]
        for r in analysis.get("recommendations", []):
            lines.append(f"- {r}")
        return "\n".join(lines).encode("utf-8")
